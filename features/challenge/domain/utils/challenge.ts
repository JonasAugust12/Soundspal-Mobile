function normalizeExplanationSentence(sentence: string): string {
    return sentence.trim().replace(/\s+/g, ' ');
}

/** Map nhận xét AI tiếng Anh sang tiếng Việt (câu lạ giữ nguyên). */
export function localizeScoreExplanation(explanation: string | null | undefined): string {
    if (!explanation) return '';

    const parts = explanation
        .split(/(?<=[.!?])\s+/)
        .map(normalizeExplanationSentence)
        .filter(Boolean);

    return parts
        .map((part) => {
            const withPeriod =
                part.endsWith('.') || part.endsWith('!') || part.endsWith('?') ? part : `${part}.`;
            return EXPLANATION_EN_TO_VI[withPeriod] ?? EXPLANATION_EN_TO_VI[part] ?? part;
        })
        .join(' ');
}
